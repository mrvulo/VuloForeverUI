# ---------------------------------------------------------------------------
# tools/flight_paths.py -- the length of every flight path, from the client's
# own data, for the flight bar (Modules/QoL/Flight.lua).
#
#   python3 tools/flight_paths.py [build]
#
# Reads TaxiPath (from node, to node) and TaxiPathNode (the waypoints the ride
# follows) for the Forever client (product "wowf") from wago.tools, adds up
# the distance between consecutive waypoints of each path, and writes
# Modules/QoL/FlightPathData.lua. Without a build: the newest wowf build.
#
# Measured against 75 flown routes (2026-11-21): a ride takes
# length / 30 yards a second + 0.25 s, mean error 0.2 s, worst 3 s; a ride over
# several paths is the sum of their lengths. Run again after a client patch.
# ---------------------------------------------------------------------------
import csv, io, json, math, os, sys, urllib.request

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "addon-data-tool"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")

def table(name, build):
    return list(csv.DictReader(io.StringIO(fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build)))))

if __name__ == "__main__":
    build = sys.argv[1] if len(sys.argv) > 1 else json.loads(fetch("https://wago.tools/api/builds"))["wowf"][0]["version"]
    paths = {int(r["ID"]): (int(r["FromTaxiNode"]), int(r["ToTaxiNode"])) for r in table("TaxiPath", build)}
    points = {}
    for r in table("TaxiPathNode", build):
        points.setdefault(int(r["PathID"]), []).append(
            (int(r["NodeIndex"]), int(r["ContinentID"]), float(r["Loc_0"]), float(r["Loc_1"]), float(r["Loc_2"])))
    yards = {}
    for pid, pts in points.items():
        if pid not in paths:
            continue
        pts.sort()
        total = 0.0
        for a, b in zip(pts, pts[1:]):
            if a[1] == b[1]:                     # a jump between continents is no distance flown
                total += math.dist(a[2:], b[2:])
        if total > 0:
            src, dst = paths[pid]
            yards.setdefault(src, {})[dst] = round(total, 1)
    rows = []
    for src in sorted(yards):
        inner = ", ".join("[%d] = %s" % (dst, yards[src][dst]) for dst in sorted(yards[src]))
        rows.append("    [%d] = { %s }," % (src, inner))
    out = (
        "-- VuloForeverUI / Modules / QoL / FlightPathData\n"
        "--\n"
        "-- GENERATED by tools/flight_paths.py from the client data of build %s.\n"
        "-- Do not edit by hand. The length in yards of every flight path,\n"
        "-- [from node ID] = { [to node ID] = yards }: the flight bar turns it into\n"
        "-- the ride's time (Flight.lua, routeTime).\n"
        "local _, ns = ...\n\n"
        "ns.FlightPathYards = {\n%s\n}\n" % (build, "\n".join(rows))
    )
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "Modules", "QoL", "FlightPathData.lua")
    open(dst, "w", encoding="utf-8").write(out)
    print("wrote", os.path.normpath(dst), "-", sum(len(v) for v in yards.values()), "paths, build", build)
